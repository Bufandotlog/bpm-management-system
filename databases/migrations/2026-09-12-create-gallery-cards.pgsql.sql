CREATE TABLE IF NOT EXISTS gallery_cards (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periode_id INTEGER NOT NULL REFERENCES periode_kepengurusan(id) ON DELETE CASCADE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  image_path VARCHAR(500) DEFAULT NULL,
  title VARCHAR(255) NOT NULL,
  subtitle VARCHAR(500) NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_gallery_cards_period_order
  ON gallery_cards (periode_id, sort_order, id);
